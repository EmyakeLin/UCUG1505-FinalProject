import assert from 'node:assert/strict';
import {BRAIN,createBrain,inputVector,predict,train,discover,remember,replay,exportBrain,importBrain} from './cognition.mjs';
import {planFor,proposal,resolveCouncil,updateBelief,welcomeReady,fetchIngredients,cookMeal,processParts,collectPart} from './society-rules.mjs';
const body={energy:.6,fatigue:.3,mood:{pleasure:.2,arousal:.5,safety:.5,connection:.4}};
const input=inputVector(body,[.3,.2,.4,.7,.5,0,.2,.1],'rest','garden-1');
assert.equal(input.length,BRAIN.inputs);
const first=createBrain(42),second=createBrain(42);
for(const brain of [first,second])discover(brain,'garden-1',[.3,.2,.4,.7,.5,0,.2,.1],{x:1,z:2},0);
for(let trial=0;trial<220;trial++){
 remember(first,{place:'garden-1',input,target:[0,.2,.45,.5,.1],source:'self',time:trial});
 remember(second,{place:'garden-1',input,target:[0,-.1,-.4,-.4,.1],source:'self',time:trial});
}
assert.ok(predict(first,input)[3]>.35);assert.ok(predict(second,input)[3]<-.25);
for(let trial=0;trial<350;trial++)train(second,input,[0,.2,.45,.5,.1]);
assert.ok(predict(second,input)[3]>.35,'New experience must revise the earlier belief');
const frozen=exportBrain(first);first.frozen=true;train(first,input,[1,1,-1,-1,-1]);replay(first,()=>.2);assert.deepEqual(first.w1,frozen.w1);assert.deepEqual(first.w2,frozen.w2);
assert.equal(first.episodes.length,BRAIN.episodes);
const restored=importBrain(JSON.parse(JSON.stringify(second)));assert.deepEqual(predict(restored,input),predict(second,input));
const invalid=exportBrain(second);invalid.w1[0]=Infinity;assert.throws(()=>importBrain(invalid));
const observer=createBrain(42),energyWeights=observer.w2.slice(0,BRAIN.hidden+1);
discover(observer,'garden-1',[.3,.2,.4,.7,.5,0,.2,.1],{x:1,z:2},0);
remember(observer,{place:'garden-1',input,target:[1,1,.3,.3,.3],source:'observed',teacher:'friend',time:1});
assert.deepEqual(observer.w2.slice(0,BRAIN.hidden+1),energyWeights,'Observation must not directly supervise private energy');
assert.equal(observer.known['garden-1'].visits,0);assert.equal(observer.known['garden-1'].observations,1);
const novice=createBrain(42);
for(let trial=0;trial<50;trial++)remember(observer,{place:'garden-1',input,target:[0,0,.5,.5,.3],source:'observed',teacher:'friend',time:trial});
assert.ok(Math.abs(predict(observer,input)[3]-.5)<Math.abs(predict(novice,input)[3]-.5),'Observed public outcomes give a useful prior');
assert.deepEqual(planFor('repair',{repairKnown:true,cartKnown:true,processingKnown:true}),['process','collect-part','repair']);
assert.deepEqual(planFor('repair',{repairKnown:true}),[]);
assert.deepEqual(planFor('repair',{repairKnown:true,cartKnown:true,processingKnown:true,partsKnown:true}),['collect-part','repair']);
assert.deepEqual(planFor('meal',{carryFood:true}),[],'A carried ingredient does not reveal an unknown kitchen');
assert.equal(resolveCouncil(['food','rotation']),null);assert.equal(resolveCouncil(['food','food','rotation']),'food');
assert.equal(proposal({shortage:1,energy:.3,fatigue:.2,labour:0,uncertainty:.1}),'food');
let belief;for(const measurement of [1,2,3])belief=updateBelief(belief,measurement);assert.equal(belief.mean,2);assert.equal(belief.count,3);
assert.equal(welcomeReady({population:4,beds:6,food:6,elapsed:121}),true);assert.equal(welcomeReady({population:4,beds:4,food:6,elapsed:121}),false);
const bowl={bowl:3.5},carry={food:0,part:0},kitchen={meals:5},station={raw:1,parts:0};
assert.ok(fetchIngredients(bowl,carry));assert.equal(bowl.bowl,1.5);assert.equal(carry.food,2);
assert.ok(cookMeal(kitchen,carry));assert.equal(kitchen.meals,6);assert.equal(carry.food,1);
assert.equal(cookMeal(kitchen,carry),false);assert.equal(bowl.bowl+carry.food+kitchen.meals,8.5);
assert.ok(processParts(station));assert.equal(station.raw,0);assert.equal(station.parts,2);assert.equal(processParts(station),false);
assert.ok(collectPart(station,carry));assert.equal(station.parts,1);assert.equal(carry.part,1);
console.log('Cognition checks passed: independent learning, revision, frozen controls, observed/private feedback, replay, persistence, plans, research statistics, and councils.');
