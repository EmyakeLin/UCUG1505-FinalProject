import assert from 'node:assert/strict';
import {createBrain,exportBrain,importBrain} from './cognition.mjs';
import {romanceState,feelings,spendTime,canDate,wantsDate,confirmBond} from './romance-rules.mjs';
const resident=index=>({index,brain:createBrain(index+1),energy:.8,fatigue:.2,mood:{pleasure:.6,safety:.8}});
const first=resident(0),second=resident(1),third=resident(2);
assert.equal(canDate(first,second),false,'陌生居民不直接约会');
spendTime(first,second,30,'play');
assert.equal(canDate(first,second),true,'相处后双向好感允许尝试邀请');
assert.equal(confirmBond(first,second,30),false,'好感不能跳过实际约会');
spendTime(first,second,24,'date');
assert.equal(confirmBond(first,second,54),true,'满足双方实际相处与约会条件后确认关系');
assert.equal(romanceState(second).partner,0,'索引为零的伴侣不能被当作未配对');
assert.equal(confirmBond(first,second,55),false,'已确认关系不重复触发');
spendTime(first,third,90,'play');
assert.equal(canDate(first,third),false,'已有伴侣仍可交朋友，但不会同时约另一位');
const restored=resident(1);restored.brain=importBrain(exportBrain(second.brain));
assert.equal(romanceState(restored).partner,0);
assert.equal(feelings(restored,first).dateSeconds,24,'沿用原有认知存档保留关系经历');
const oneWay=resident(3),uninterested=resident(4);
Object.assign(feelings(oneWay,uninterested,true),{affection:.95,sharedSeconds:80,dateSeconds:20});
assert.equal(canDate(oneWay,uninterested),false,'单向喜欢不能替另一方决定');
assert.equal(confirmBond(oneWay,uninterested,99),false);
const tired=resident(5);tired.fatigue=.9;
assert.equal(wantsDate(tired,0),false,'疲劳时即使抽样有利也不接受');
spendTime(tired,oneWay,20,'date');
assert.equal(feelings(tired,oneWay),undefined,'不舒适相处不自动增加好感');
assert.equal(wantsDate(uninterested,.99),false,'状态允许仍可拒绝邀请');
assert.equal(wantsDate(uninterested,0),true);
const nearbyA=resident(6),nearbyB=resident(7);
spendTime(nearbyA,nearbyB,600,'nearby');
assert.equal(canDate(nearbyA,nearbyB),false,'仅挤在一起不替代真实互动');
assert.equal(feelings(nearbyA,nearbyB).affection,1,'长时间输入仍限制好感在有效范围');
console.log('Relationship data checks passed: mutual choice, shared experience, needs, exclusivity, bounded values, and old brain persistence. No UI or world simulation executed.');
