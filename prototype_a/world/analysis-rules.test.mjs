import assert from 'node:assert/strict';
import {createBrain,discover,remember,predict,inputVector} from './cognition.mjs';
import {recordLife,validateSnapshot,evaluateObject,habitRows,objectsFor,inputSensitivity,defaultAction} from './analysis-rules.mjs';

const makeResident=index=>({index,name:'测试居民'+index,color:0xffe8bf,energy:.6,fatigue:.3,mood:{pleasure:.2,arousal:.5,safety:.7,connection:.5},company:false,action:'idle',brain:createBrain(index+1)});
const first=makeResident(0),second=makeResident(1),visible=[.1,.1,.1,.8,.7,.5,.3,.2];
const place={id:'initial-sunlight',name:'测试阳光中心',kind:'building',key:'sunlight'},friend={id:'friend-1',name:second.name,kind:'resident',index:1};
discover(first.brain,place.id,visible,{x:1,z:2},0);
discover(first.brain,friend.id,visible,{x:2,z:3},0);
const input=inputVector({...first,familiarity:0},visible,'rest',place.id);
remember(first.brain,{place:place.id,input,target:[.1,.2,.3,.4,.5],source:'self',time:5,action:'sun'});
remember(first.brain,{place:place.id,input,target:[.9,.9,.6,.6,.6],source:'observed',time:8,action:'sun'});
recordLife(first,2,2);recordLife(first,3,5);
first.action='sun';first.slot={facility:{id:place.id}};recordLife(first,4,9);
assert.equal(first.brain.observation.total,9);
assert.equal(first.brain.observation.recent.length,2,'连续同类同对象片段合并');
assert.equal(first.brain.observation.objects[place.id],4);
assert.ok(Math.abs(habitRows(first).reduce((sum,row)=>sum+row.fraction,0)-1)<1e-12,'活动占比来自实际时长');
const noTime=JSON.stringify(first.brain.observation);recordLife(first,0,9);assert.equal(JSON.stringify(first.brain.observation),noTime);
const frozen=JSON.stringify(first.brain);
const actual=evaluateObject(first,place,'rest',false);
assert.deepEqual(actual.prediction,predict(first.brain,actual.input),'分析使用原有网络的真实预测');
assert.deepEqual(actual.actual,[.1,.2,.3,.4,.5],'间接经历不混入亲身结果');
assert.equal(actual.matched.length,1);assert.equal(actual.evidence.length,2);
assert.equal(evaluateObject(first,place,'work').actual,null,'不同动作不混作同类历史');
assert.equal(evaluateObject(first,{id:'unseen'},'try'),null,'未知对象不伪造态度');
const standard=evaluateObject(first,place,'rest',true);
assert.equal(standard.body.familiarity,.5);assert.equal(standard.body.company,false);
assert.deepEqual(inputSensitivity(first,actual).map(item=>item.change.length),[5,5,5,5,5,5]);
assert.equal(JSON.stringify(first.brain),frozen,'分析与敏感性计算不训练或写回大脑');
assert.equal(defaultAction(friend),'social');assert.equal(defaultAction(place),'rest');
first.brain.romance={partner:1,since:9,nextInvite:20};second.brain.romance={partner:0,since:9,nextInvite:20};
const data={type:'ucug1505-life-analysis',version:1,time:9,residents:[first,second],objects:[place,friend,{id:'friend-0',name:first.name,kind:'resident'}]};
const clean=validateSnapshot(data);
assert.equal(clean.residents[1].brain.romance.partner,0,'双向关系包含零号居民');
assert.equal(clean.residents[1].brain.observation,undefined,'旧存档没有时长就保持缺失');
assert.equal(objectsFor(clean,clean.residents[0]).some(object=>object.id==='friend-0'),false,'不把自身列为社交对象');
assert.throws(()=>validateSnapshot({layers:{}}),/纯权重/);
const bad=JSON.parse(JSON.stringify(data));bad.residents[0].brain.w1[0]=null;assert.throws(()=>validateSnapshot(bad),/权重/);
const badTime=JSON.parse(JSON.stringify(data));badTime.residents[0].brain.observation.activities.rest=-1;assert.throws(()=>validateSnapshot(badTime),/时长/);
const badIdentity=JSON.parse(JSON.stringify(data));badIdentity.residents[1].index=0;assert.throws(()=>validateSnapshot(badIdentity),/身份/);
for(let index=0;index<130;index++){second.action=index%2?'chat':'idle';recordLife(second,1,index+1);}
assert.equal(second.brain.observation.recent.length,120,'轨迹有上限');assert.equal(second.brain.observation.total,130,'累计时长不随轨迹截断');
second.health={state:'dead'};const stopped=second.brain.observation.total;recordLife(second,10,140);assert.equal(second.brain.observation.total,stopped,'离世后不继续累计生活时长');
console.log('Analysis data checks passed: time accounting, provenance, unknown objects, original-network predictions, read-only probes, bounded timeline, validation, and snapshot persistence. No UI executed.');
