import assert from 'node:assert/strict';
import {WINTER,worldClimate,localDanger,healthOf,comaCause,advanceComa,applyKit,fullyRecovered,prepareKit,collectKit,retimeWorld} from './winter-rules.mjs';
assert.equal(WINTER.daySeconds,1440);assert.equal(WINTER.deathNightSeconds,18*60);
assert.equal(worldClimate(0).hour,12);assert.equal(worldClimate(0).daylight,12);
assert.equal(worldClimate(7200).daylight,9);assert.equal(worldClimate(14400).daylight,6);assert.equal(worldClimate(28800).nightHours,18);
assert.equal(worldClimate(14400).danger,0);
const dusk=worldClimate(14400+180);assert.equal(dusk.phase,'黄昏');assert.equal(dusk.danger,1);assert.equal(dusk.isNight,true);
assert.equal(worldClimate(14400+270-.001).fullNight,false);assert.equal(worldClimate(14400+270).danger,3);
const dawn=worldClimate(14400+1260);assert.equal(dawn.phase,'黎明');assert.equal(dawn.danger,1);assert.equal(dawn.isNight,false);
assert.equal(localDanger(worldClimate(15000),true),1.5);assert.equal(localDanger(worldClimate(15000),false),3);
assert.ok(Math.abs(WINTER.clinicEnergy-.009)<1e-12);assert.ok(1/WINTER.clinicEnergy<WINTER.deathNightSeconds,'床位从空能量恢复不再需要56分钟');
assert.equal(comaCause(0,.2),'energy');assert.equal(comaCause(.5,1),'rest');assert.equal(comaCause(0,1),'both');assert.equal(comaCause(.001,.999),null);
const creature={energy:0,fatigue:1,mood:{pleasure:0,safety:.5,comfort:.5}},health=healthOf(creature);health.state='coma';
assert.equal(advanceComa(health,100,true,true),false);assert.equal(health.nightSeconds,100);
assert.equal(advanceComa(health,200,false,true),false);assert.equal(health.nightSeconds,100,'白天暂停而不清零');
assert.equal(advanceComa(health,979,true,true),false);assert.equal(advanceComa(health,1,true,true),true);
assert.equal(advanceComa(health,1,true,false),false,'关闭死亡不会执行不可逆死亡');assert.equal(health.nightSeconds,1081);
assert.equal(advanceComa(health,0,false,true),true,'重新开启按累计时间判断');
assert.equal(applyKit(creature,'rest'),true);assert.equal(creature.energy,.05);assert.equal(creature.fatigue,.7);assert.equal(fullyRecovered(creature),false);
health.state='dead';assert.equal(applyKit(creature,'energy'),false,'药包不能让已死亡者复生');
assert.equal(fullyRecovered({energy:1,fatigue:0}),true);assert.equal(fullyRecovered({energy:.99,fatigue:0}),false);
const kits={energy:0,rest:0},carrier={supply:0,kit:null};
assert.equal(prepareKit(kits,carrier,'energy'),false);carrier.supply=1;assert.equal(prepareKit(kits,carrier,'energy'),true);assert.equal(carrier.supply,0);assert.equal(kits.energy,1);
assert.equal(collectKit(kits,carrier,'energy'),true);assert.equal(kits.energy,0);assert.equal(carrier.kit,'energy');assert.equal(collectKit(kits,carrier,'energy'),false);
const saved=JSON.parse(JSON.stringify({health,kits,carrier}));assert.equal(saved.health.nightSeconds,1081);assert.equal(saved.carrier.kit,'energy');
console.log('Winter/health data checks passed: day length, twilight, winter cap, shelter, coma thresholds, cumulative nights, death toggle, food conservation, treatment, and persistence. No UI or ecology simulation executed.');

assert.equal(worldClimate(60).hour,13);
assert.equal(worldClimate(1440).day,2);
const old={time:420,winterStart:0,residents:[{health:{state:'coma',nightSeconds:120}}],taskDeadline:430};
const migrated=retimeWorld(old);
assert.equal(migrated.time,420);assert.equal(migrated.taskDeadline,430);
assert.equal(migrated.winterStart,-1680);assert.equal(migrated.residents[0].health.nightSeconds,600);
assert.equal(worldClimate(migrated.time-migrated.winterStart).hour,23);
assert.equal(worldClimate(migrated.time-migrated.winterStart).day,2);
assert.equal(old.residents[0].health.nightSeconds,120);
assert.deepEqual(retimeWorld(migrated),migrated);
assert.equal(retimeWorld({time:100,residents:[]}).winterStart,100);
console.log('Clock migration passed: calendar phase, coma hours, task timestamps and repeated load preserved.');
